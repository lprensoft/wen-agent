package i18n

import "log"

// Logf 打一行运行日志，措辞按语言取。
//
// 日志与界面文案同属「给人看的」那一侧，因此走同一份语言包：装英文的人打开日志
// 看到半页中文，与设置页上冒出一行中文是同一件事。
//
// 单独给它一个函数而不是写成 log.Printf(Tf(...))，有两个理由：调用点少一层嵌套，
// 一行写得下；以及 go vet 会对「非常量的格式串」报警，而 Tf 的返回值正是那种。
// 参数形状与 Tf 一致（lang, key, 中文原文, 参数...），覆盖检查因此认得出它。
//
// 用的是**进程语言**：日志没有请求可依附，而一份中英混排的日志比哪一种语言都难读。
func Logf(lang, key, fallback string, a ...any) {
	log.Print(Tf(lang, key, fallback, a...))
}
